const logger = pino({ level: process.env.LOG_LEVEL || 'info' });

// Simple admin auth check (reuses existing ADMIN_USER/ADMIN_PASS)
function requireAdmin(req, res, next) {
  const auth = req.headers.authorization;
  if (!auth || !auth.startsWith('Basic ')) {
    return res.status(401).json({ error: 'Admin authentication required' });
  }
  const decoded = Buffer.from(auth.split(' ')[1], 'base64').toString();
  const [user, pass] = decoded.split(':');
  if (user !== process.env.ADMIN_USER || pass !== process.env.ADMIN_PASS) {
    return res.status(403).json({ error: 'Invalid credentials' });
  }
  next();
}

/**
 * GET /api/daily-article
 * Returns today's formatted article as JSON.
 * Optional ?date=YYYY-MM-DD query param.
 */
router.get('/', async (req, res) => {
  try {
    const date = req.query.date || undefined;
    const article = await getDailyArticle(date);
    if (!article) {
      return res.status(404).json({ error: 'No articles available' });
    }
    // Allow embedding from any Ralph domain
    res.set('Access-Control-Allow-Origin', '*');
    res.json({ article });
  } catch (err) {
    logger.error({ error: err.message }, 'Failed to get daily article');
    res.status(500).json({ error: 'Failed to retrieve daily article' });
  }
});

/**
 * POST /api/daily-article/refresh
 * Admin-only: clears cache for today (or ?date=) and regenerates.
 */
router.post('/refresh', requireAdmin, async (req, res) => {
  try {
    const date = req.query.date || req.body.date || undefined;
    const article = await refreshDailyArticle(date);
    if (!article) {
      return res.status(404).json({ error: 'No articles available' });
    }
    res.json({ article, refreshed: true });
  } catch (err) {
    logger.error({ error: err.message }, 'Failed to refresh daily article');
    res.status(500).json({ error: 'Failed to refresh daily article' });
  }
});

/**
 * GET /embed/daily-article
 * Self-contained HTML embed page. Works in an iframe.
 */
async function embedHandler(req, res) {
  try {
    const date = req.query.date || undefined;
    const article = await getDailyArticle(date);

    if (!article) {
      return res.status(404).send('<html><body><p>No article available today.</p></body></html>');
    }

    const html = renderEmbedHtml(article);
    res.set('Content-Type', 'text/html');
    res.set('Access-Control-Allow-Origin', '*');
    res.send(html);
  } catch (err) {
    logger.error({ error: err.message }, 'Failed to render daily article embed');
    res.status(500).send('<html><body><p>Error loading article.</p></body></html>');
  }
}

function escapeHtml(str) {
  if (!str) return '';
  return str.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

