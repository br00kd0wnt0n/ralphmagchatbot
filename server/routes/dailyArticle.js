/**
 * GET /api/daily-article/schedule?days=7
 * Returns metadata for today + N days ahead (no GPT-4o calls).
 */
router.get('/schedule', (req, res) => {
  try {
    const days = Math.min(Math.max(parseInt(req.query.days) || 7, 1), 30);
    const today = new Date().toISOString().split('T')[0];
    const schedule = previewArticlesForRange(today, days);
    res.json({ schedule });
  } catch (err) {
    logger.error({ error: err.message }, 'Failed to get article schedule');
    res.status(500).json({ error: 'Failed to retrieve schedule' });
  }
});

